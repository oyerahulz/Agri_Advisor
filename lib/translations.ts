export function translatePattern(en: string, lang: "mr" | "ta" | "te"): string | undefined {
  for (const p of PATTERNS[lang]) {
    const m = en.match(p.re);
    if (m) return p.build(m[1], m[2]);
  }
  return undefined;
}

